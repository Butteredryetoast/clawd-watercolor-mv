#!/usr/bin/env python3
"""Generate src/lyrics.js and src/shotlist.js from the source data.

  python3 tools/build_data.py [--json=assets/歌名-歌词时间线.json]

Inputs (paths relative to project root):
  the lyric-timeline JSON   --json, else the only assets/*.json (keys: audio_duration_seconds, status, credits[],
                            lyrics[] with id, text, start_seconds, end_seconds, needs_audio_review, review_priority)
  STORYBOARD.md             the confirmed storyboard: "## N · 章名" headings + rows "| a–b | 歌词 | 画面 | 表演 | 出 |"

Outputs:
  src/lyrics.js    const LY = [[start, end, text, id, priority, needsReview, text_zh], ...]; const CREDITS = [...]
                   (text_zh = the translation for bilingual subtitles, null when the JSON has none)
  src/shotlist.js  const SHOTLIST = [{ ch, chName, a, b, lyric, shot, act, out }, ...]
The lyric timings are NOT human verified; the review flags are carried through unchanged.
"""
import sys, json, re, pathlib

ROOT = pathlib.Path(__file__).resolve().parent.parent
args = dict(a.lstrip('-').split('=', 1) for a in sys.argv[1:] if '=' in a)
if 'json' in args: JSON = ROOT / args['json']
else:
    found = sorted((ROOT / 'assets').glob('*.json'))
    if len(found) != 1: sys.exit(f'pass --json=… (assets/ has {len(found)} JSON files: {[f.name for f in found]})')
    JSON = found[0]
src = json.loads(JSON.read_text('utf-8'))

js = [f'// lyrics.js: GENERATED by tools/build_data.py from {JSON.relative_to(ROOT)}. Do not edit by hand.',
      f'// status: {src["status"]}. Starts = original LRC (kept); ends = ' + ('machine alignment estimates.' if 'align' in src['status'] else 'length guesses (LRC only).'),
      '// Not human verified. priority "high" = flagged for re-listening before the final cut.',
      '// [start, end, text, id, priority, needsReview, text_zh]',
      'const LY = [']
for l in src['lyrics']:
    js.append(f'  [{l["start_seconds"]:.2f}, {l["end_seconds"]:.2f}, {json.dumps(l["text"], ensure_ascii=False)}, '
              f'{l["id"]}, "{l.get("review_priority", "high" if l["needs_audio_review"] else "normal")}", {str(bool(l["needs_audio_review"])).lower()}, '
              f'{json.dumps(l.get("text_zh"), ensure_ascii=False)}],')
js.append('];')
js.append('const CREDITS = ' + json.dumps([[c['time_seconds'], c['text']] for c in src['credits']], ensure_ascii=False) + ';')
js.append('const LYRIC_STATUS = ' + json.dumps({'status': src['status'], 'humanVerified': False,
          'reviewHigh': [l['id'] for l in src['lyrics'] if l.get("review_priority", "high" if l["needs_audio_review"] else "normal") == "high"]}, ensure_ascii=False) + ';')
(ROOT / 'src/lyrics.js').write_text('\n'.join(js) + '\n', 'utf-8')

# ---- storyboard → shot list ----
md = (ROOT / 'STORYBOARD.md').read_text('utf-8').splitlines()
shots, ch, chName = [], None, ''
head = re.compile(r'^##\s+(\d+)\s*·\s*(.+?)(?:（|\(|$)')
row = re.compile(r'^\|\s*([\d.]+)\s*[–-]\s*([\d.]+)\s*\|(.*)\|\s*$')
for line in md:
    m = head.match(line)
    if m: ch, chName = int(m.group(1)), m.group(2).strip(); continue
    m = row.match(line)
    if m and ch is not None:
        cells = [c.strip() for c in m.group(3).split('|')]
        while len(cells) < 4: cells.append('')
        shots.append({'ch': ch, 'chName': chName, 'a': float(m.group(1)), 'b': float(m.group(2)),
                      'lyric': cells[0], 'shot': cells[1], 'act': cells[2], 'out': cells[3]})
out = ['// shotlist.js: GENERATED by tools/build_data.py from STORYBOARD.md. Do not edit by hand.',
       '// Used by the timeline placeholder and the studio info panel; chapter code registers the real shots.',
       'const SHOTLIST = [']
for s in shots: out.append('  ' + json.dumps(s, ensure_ascii=False) + ',')
out.append('];')
(ROOT / 'src/shotlist.js').write_text('\n'.join(out) + '\n', 'utf-8')

# continuity sanity check: shots must tile [0, duration] with no gaps
gaps = [(p['b'], q['a']) for p, q in zip(shots, shots[1:]) if abs(p['b'] - q['a']) > 1e-6]
print(f'{len(src["lyrics"])} lyrics, {len(shots)} shots, span {shots[0]["a"]}–{shots[-1]["b"]} s, gaps: {gaps or "none"}')
